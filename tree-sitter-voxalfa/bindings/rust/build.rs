use std::io::Write;

fn main() {
    let src_dir = std::path::Path::new("src");

    let mut c_config = cc::Build::new();
    c_config.std("c11").include(src_dir);

    #[cfg(target_env = "msvc")]
    c_config.flag("-utf-8");

    if std::env::var("TARGET").unwrap() == "wasm32-unknown-unknown" {
        let Ok(wasm_headers) = std::env::var("DEP_TREE_SITTER_LANGUAGE_WASM_HEADERS") else {
            panic!("Environment variable DEP_TREE_SITTER_LANGUAGE_WASM_HEADERS must be set by the language crate");
        };

        c_config.include(&wasm_headers);
    }

    let parser_path = src_dir.join("parser.c");
    c_config.file(&parser_path);
    println!("cargo:rerun-if-changed={}", parser_path.to_str().unwrap());

    generate_node_types(&parser_path).expect("failed to generate node types");

    let scanner_path = src_dir.join("scanner.c");
    if scanner_path.exists() {
        c_config.file(&scanner_path);
        println!("cargo:rerun-if-changed={}", scanner_path.to_str().unwrap());
    }

    c_config.compile("tree-sitter-voxalfa");

    println!("cargo:rustc-check-cfg=cfg(with_highlights_query)");
    if !"queries/highlights.scm".is_empty()
        && std::path::Path::new("queries/highlights.scm").exists()
    {
        println!("cargo:rustc-cfg=with_highlights_query");
    }
    println!("cargo:rustc-check-cfg=cfg(with_injections_query)");
    if !"queries/injections.scm".is_empty()
        && std::path::Path::new("queries/injections.scm").exists()
    {
        println!("cargo:rustc-cfg=with_injections_query");
    }
    println!("cargo:rustc-check-cfg=cfg(with_locals_query)");
    if !"queries/locals.scm".is_empty() && std::path::Path::new("queries/locals.scm").exists() {
        println!("cargo:rustc-cfg=with_locals_query");
    }
    println!("cargo:rustc-check-cfg=cfg(with_tags_query)");
    if !"queries/tags.scm".is_empty() && std::path::Path::new("queries/tags.scm").exists() {
        println!("cargo:rustc-cfg=with_tags_query");
    }
}

/// Generates Rust constants for the node types from the `ts_symbol_identifiers`
/// enum in `src/parser.c`.
fn generate_node_types(parser_path: &std::path::Path) -> Result<(), std::io::Error> {
    let parser_file = std::fs::read_to_string(parser_path)?;

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let output_path = std::path::Path::new(&out_dir).join("node_types.rs");

    let mut output_file = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(output_path)?;

    let mut buffer = String::from(
        "// This file is automatically generated by `build.rs`, do not edit manually.\n\n",
    );

    let mut process_flag = false;

    for line in parser_file.lines() {
        if line.contains("enum ts_symbol_identifiers {") {
            buffer.push_str("pub mod node_types {\n");
            process_flag = true;
        }

        if !process_flag {
            continue;
        }

        if let Some(rest) = line.trim_start().strip_prefix("sym_") {
            let parts = rest.split_whitespace().collect::<Vec<_>>();
            let name = parts[0];

            if name.starts_with("_") {
                continue;
            }

            let lhs = name.to_uppercase();
            let rhs = parts[2].replace(",", ";");
            let line = format!("    pub const {lhs}: u16 = {rhs}\n");

            buffer.push_str(&line);
        }

        if line.contains("}") {
            buffer.push_str("}\n");
            break;
        }
    }

    output_file.write_all(buffer.as_bytes())
}
